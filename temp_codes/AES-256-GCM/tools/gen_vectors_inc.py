                     
"""Convert tests/vectors.json into a C header tests/test_vectors.inc.

The vectors are generated independently (via the `cryptography` lib) so they
act as an oracle for gcm_core (design doc §0.5 / §6: "NIST AES-GCM test vectors
are sufficient to validate this subsystem in complete isolation").
"""
import json, os

here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))               
vec = json.load(open(os.path.join(here, "tests", "vectors.json")))

def c_bytes(hexs):
    b = bytes.fromhex(hexs) if hexs else b""
    out = ", ".join("0x%02x" % x for x in b) if b else "0x00"
    return out, len(b)

lines = []
lines.append("/* Generated by tools/gen_vectors.py + tools/gen_vectors_inc.py. Do not edit. */")
lines.append("#ifndef TEST_VECTORS_INC")
lines.append("#define TEST_VECTORS_INC")
lines.append("")
lines.append("typedef struct {")
lines.append("    const char *label;")
lines.append("    const uint8_t key[AEAD_KEY_LEN];")
lines.append("    const uint8_t iv[AEAD_NONCE_LEN];")
lines.append("    const uint8_t *aad;   size_t aad_len;")
lines.append("    const uint8_t *pt;    size_t pt_len;")
lines.append("    const uint8_t *ct;    size_t ct_len;")
lines.append("    const uint8_t tag[AEAD_TAG_LEN];")
lines.append("} gcm_vector_t;")
lines.append("")
lines.append("static const gcm_vector_t gcm_vectors[] = {")

for v in vec:
    key, _ = c_bytes(v["key"])
    iv, _ = c_bytes(v["iv"])
    aad, aad_len = c_bytes(v["aad"])
    pt, pt_len = c_bytes(v["pt"])
    ct, ct_len = c_bytes(v["ct"])
    tag, _ = c_bytes(v["tag"])
    lines.append("    {")
    lines.append(f'        .label = "{v["label"]}",')
    lines.append(f"        .key = {{ {key} }},")
    lines.append(f"        .iv  = {{ {iv} }},")
    lines.append(f"        .aad = (const uint8_t[]){{ {aad} }}, .aad_len = {aad_len},")
    lines.append(f"        .pt  = (const uint8_t[]){{ {pt} }}, .pt_len = {pt_len},")
    lines.append(f"        .ct  = (const uint8_t[]){{ {ct} }}, .ct_len = {ct_len},")
    lines.append(f"        .tag = {{ {tag} }},")
    lines.append("    },")

lines.append("};")
lines.append(f"#define GCM_VECTOR_COUNT {len(vec)}")
lines.append("")
lines.append("#endif /* TEST_VECTORS_INC */")

open(os.path.join(here, "tests", "test_vectors.inc"), "w").write("\n".join(lines) + "\n")
print(f"wrote {len(vec)} vectors to tests/test_vectors.inc")